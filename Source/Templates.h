/*
  ==============================================================================

    Templates.h
    "New voice" templates. Bases = the SY77's own INIT VOICE, taken from real dumps in
    docs/ (most frequent copy: type 3 = 1 AFM POLY in 77 dumps, type 8 = 1 AFM + 1 AWM
    with operator 1 only, same convention as type 3). Derived templates are built by
    patching those bytes (offsets as in SyVoice::voiceBlobToParams):
      - FM 2 operators : Init AFM + algorithm 1 (serial chain) + OP2 output level.
      - Init AWM       : the AWM element of the type-8 init, re-framed as type 5.
    All of them go to the EDIT BUFFER only (retargetVoiceToEditBuffer).

  ==============================================================================
*/

