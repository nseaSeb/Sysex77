    struct Info { const char* name; const char* description; };
    inline const std::vector<Info>& list()
    {
        static const std::vector<Info> l {
            { "Init AFM",        "1 AFM element, operator 1 only, sine, neutral envelopes" },
            { "FM 2 operators",  "Carrier + modulator, serial algorithm" },
            { "Init AWM",        "1 AWM element, open filter" },
            { "AFM + AWM layer", "2 elements, one of each" } };
        return l;
    }

    inline void fixFrame (juce::MemoryBlock& m)
    {
        auto* b = (juce::uint8*) m.getData();
        const int n = (int) m.getSize();
        const int count = n - 8;                       // bytes between the 6-byte header and checksum
        b[4] = (juce::uint8) ((count >> 7) & 0x7F);
        b[5] = (juce::uint8) (count & 0x7F);
        b[n - 2] = SyVoice::yamahaChecksum (b + 6, n - 8);
        b[n - 1] = 0xF7;
    }

    /** Full voice bulk block (F0..F7) of template i, or empty if out of range. */
    inline juce::MemoryBlock make (int i)
    {
        juce::MemoryBlock m;
        auto setName = [] (juce::MemoryBlock& blk, const char* name)
        {
            auto* b = (juce::uint8*) blk.getData();
            for (int k = 0; k < 10; ++k)
                b[33 + k] = (juce::uint8) (name[k] != 0 ? name[k] : ' ');
        };

        if (i == 0) { m.append (kInitAfm, sizeof (kInitAfm)); }
        else if (i == 1)
        {
            m.append (kInitAfm, sizeof (kInitAfm));
            auto* b = (juce::uint8*) m.getData();
            const int base = 107;                      // element 1 of a 1-element voice
            b[base + 270] = 0;                         // ALGNUM = algorithm 1 (serial 6>5>4>3>2>1)
            b[base + 4 * 45 + 29] = 90;                // OP2 (record #4, order OP6..OP1) TL -> modulates OP1
            setName (m, "FM 2 OP   ");
        }
        else if (i == 2)
        {
            // Type 5 = header(32) + type/name/common(32..97) + 9 layer bytes + AWM block (112).
            m.append (kInitAfmAwm, 98);                         // header + common, from the type-8 init
            m.append (kInitAfmAwm + 107, 9);                    // layer bytes of element 2 (the AWM one)
            m.append (kInitAfmAwm + 116 + 357, 112);            // AWM element block
            const juce::uint8 tail[2] = { 0, 0xF7 };
            m.append (tail, 2);
            ((juce::uint8*) m.getData())[32] = 5;               // type = 1 AWM POLY
            setName (m, "INIT AWM  ");
        }
        else if (i == 3) { m.append (kInitAfmAwm, sizeof (kInitAfmAwm)); setName (m, "INIT LAYER"); }
        else return {};

        fixFrame (m);
        return m;
    }
